#!/usr/bin/env node
// Auto-bump version, commit, and tag the current repo state.

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();

const sh = (cmd) =>
  execSync(cmd, { cwd: ROOT, stdio: ['pipe', 'pipe', 'pipe'] }).toString().trim();
const shSafe = (cmd, fallback) => {
  try { return sh(cmd); } catch { return fallback; }
};

const currentTag = shSafe(
  'git describe --tags --abbrev=0 --match "v[0-9]*"',
  'v0.0.0'
);
const m = currentTag.match(/^v(\d+)\.(\d+)\.(\d+)$/);
if (!m) {
  console.error(`Cannot parse current tag: ${currentTag}`);
  process.exit(1);
}
const [, major, minor, patch] = m;
const newTag = `v${major}.${minor}.${parseInt(patch, 10) + 1}`;

const commit = sh('git rev-parse --short HEAD');
const branch = sh('git rev-parse --abbrev-ref HEAD');
const builtAt = new Date().toISOString();
const subject = shSafe('git log -1 --pretty=%s', 'release');

const versionData = { version: newTag, commit, branch, builtAt, subject };

writeFileSync(
  join(ROOT, 'apps/web/public/version.json'),
  JSON.stringify(versionData, null, 2) + '\n'
);

writeFileSync(
  join(ROOT, 'apps/server/src/version.generated.ts'),
  `// AUTO-GENERATED by scripts/release.mjs - do not edit\nexport const APP_VERSION = ${JSON.stringify(versionData)} as const;\n`
);

console.log(`Release ${newTag} (commit ${commit}, branch ${branch})`);

const status = sh('git status --porcelain');
if (status) {
  sh('git add -A');
  sh('git commit -m "chore(release): ' + newTag + '" --no-verify');
}

try {
  sh('git rev-parse ' + newTag);
  console.error('Tag ' + newTag + ' already exists');
  process.exit(1);
} catch {}

sh('git tag -a ' + newTag + ' -m "release: ' + newTag + ' (' + subject + ')"');
console.log('Tagged ' + newTag);